const UNKNOWN = ["###", "#.#", "#.#", "#.#", "###"];

/** Letters with accents are drawn as their plain letter: Ç as C, Ã as A. */
const plain = (char) => char.normalize("NFD").replace(/\p{Mn}/gu, "");

/**
 * The glyph a character is drawn with, as rows of booleans (true is ink).
 * @param {string} char
 * @returns {boolean[][]}
 */
export function glyph(char) {
  const upper = plain(char).toUpperCase();
  const rows = GLYPHS[upper] ?? GLYPHS[char] ?? UNKNOWN;
  return rows.map((row) => [...row].map((cell) => cell === "#"));
}
