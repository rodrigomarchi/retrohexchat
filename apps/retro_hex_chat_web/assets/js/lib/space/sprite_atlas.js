// Build an avatar descriptor from its geometry. The game's "sword" action maps to
// the "attack" block; an avatar without idle/idle2/sword/sleep falls back to walk.
function isoAvatar(id) {
  const geo = ISO_GEO[`iso_${id}`];
  const cols = geo.cols;
  const block = (rows) => ({ frameW: geo.frameW, frameH: geo.frameH, cols, rows });
  const desc = { sheet: `av_iso_${id}`, scale: 1 };
  for (const [anim, rows] of Object.entries(geo.anims)) {
    desc[anim === "attack" ? "sword" : anim] = block(rows);
  }
  return desc;
}

const AVATARS = Object.freeze(Object.fromEntries(ROSTER.map((id) => [id, isoAvatar(id)])));

// Per-avatar content bounds inside the (padded) frame, in native frame px:
// `top` = the highest opaque row (crown of the head), `foot` = the lowest (the
